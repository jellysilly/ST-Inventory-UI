const cache = new Map();

function toSvg(rows, mono) {
    const rects = [];
    for (let y = 0; y < rows.length; y++) {
        const row = rows[y];
        let x = 0;
        while (x < row.length) {
            const ch = row[x];
            if (ch === '.' || !PALETTE[ch]) {
                x++;
                continue;
            }
            let run = 1;
            while (x + run < row.length && row[x + run] === ch) run++;
            const fill = mono ? '#000' : PALETTE[ch];
            rects.push(`<rect x="${x}" y="${y}" width="${run}" height="1" fill="${fill}"/>`);
            x += run;
        }
    }
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">${rects.join('')}</svg>`;
}

/**
 * Returns a data URL for a sprite, or null when the key is unknown.
 * @param {string} key
 * @param {boolean} [mono] render as a flat silhouette
 */
export function spriteUrl(key, mono = false) {
    const rows = SPRITES[key];
    if (!rows) return null;
    const cacheKey = `${key}|${mono ? 1 : 0}`;
    if (!cache.has(cacheKey)) {
        cache.set(cacheKey, 'data:image/svg+xml;utf8,' + encodeURIComponent(toSvg(rows, mono)));
    }
    return cache.get(cacheKey);
}

