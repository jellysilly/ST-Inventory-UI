let lang = 'en';

export function setLanguage(value) {
    if (value === 'ru' || value === 'en') {
        lang = value;
        return;
    }
    let locale = '';
    try {
        locale = SillyTavern.getContext().getCurrentLocale?.() || localStorage.getItem('language') || navigator.language || '';
    } catch {
        locale = navigator.language || '';
    }
    lang = /^(ru|uk|be)/i.test(locale) ? 'ru' : 'en';
}

export function getLanguage() {
    return lang;
}

export function t(key, ...args) {
    const str = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
    return args.length ? str.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? '')) : str;
}
